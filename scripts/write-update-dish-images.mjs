function sqlStr(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

const values = Object.entries(dishUrls)
  .map(([name, url]) => `  (${sqlStr(name)}, ${sqlStr(url)})`)
  .join(",\n");

const catValues = Object.entries(categoryFallback)
  .map(([name, url]) => `  (${sqlStr(name)}, ${sqlStr(url)})`)
  .join(",\n");

const sql = `-- Populate dishes.image_url with high-resolution Unsplash photos.
-- Match by Georgian dish name, then fill leftovers by category.

begin;

update dishes d
set image_url = v.url
from (
  values
${values}
) as v(name, url)
where d.name = v.name;

update dishes d
set image_url = v.url
from categories c
join (
  values
${catValues}
) as v(category_name, url) on c.name = v.category_name
where d.category_id = c.id
  and (d.image_url is null or btrim(d.image_url) = '');

commit;
`;

writeFileSync(
  new URL("../supabase/update-dish-images.sql", import.meta.url),
  sql,
  "utf8",
);
