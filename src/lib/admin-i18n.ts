export type AdminUiKey = keyof (typeof adminUi)["en"];
export type AdminCopy = (typeof adminUi)[AdminLocale];

export function adminT(locale: AdminLocale, key: AdminUiKey) {
  return adminUi[locale][key];
}

export function statusLabel(
  locale: AdminLocale,
  status: "pending" | "preparing" | "ready" | "served" | "cancelled",
) {
  return adminUi[locale][status];
}

export function engineeringRoleLabel(locale: AdminLocale, role: string) {
  const copy = adminUi[locale];
  if (role === "star") return copy.star;
  if (role === "puzzle") return copy.puzzle;
  if (role === "waste-risk") return copy.wasteRisk;
  if (role === "plowhorse") return copy.plowhorse;
  return copy.standard;
}
